for name, (dtype, a, b) in CASES.items():
    body = "hostname SW-1\nvlan 10\n"
    check(f"{name}: cambiar la hora o el tiempo encendido no es un cambio", same(dtype, a + body, b + body),
          clean_config(a + body, get_profile(dtype)))

# lo que SÍ es configuración se sigue viendo, también si lleva horas o fechas
KEEP = [
    ("ubiquiti_edgeswitch", "unms uiurl https://10.253.255.74"),
    ("ubiquiti_edgeswitch", "! System Description: RTK ES-18X Switch"),
    ("ubiquiti_edgeswitch", "! System Version: v1.11.1"),
    ("cisco_ios", "clock timezone EST -5 0"),
    ("cisco_ios", "banner motd ^Horario de soporte 08:00-17:00^"),
    ("cisco_ios", "ntp server 10.0.0.1"),
    ("mikrotik_routeros", "/system clock set time-zone-name=America/Bogota"),
    ("juniper_junos", "set system time-zone America/Bogota"),
    ("hp_procurve", "; Ver #14:3f.6f.f8.1d.fc.7f.ff.ff.bf.ef:a3"),
    ("vyos", '// vyos-config-version: "bgp@5:broadcast-relay@1:cluster@1"'),
    ("fortinet", "    set schedule-time 03:00"),
]
for dtype, line in KEEP:
    check(f"se conserva: «{line.strip()}»", line.rstrip() in clean_config(f"hostname X\n{line}\n", get_profile(dtype)))
check("una línea nueva como «unms uiurl» sigue siendo un cambio real",
      not same("ubiquiti_edgeswitch", "unms enable\n", "unms enable\nunms uiurl https://10.253.255.74\n"))

# primer respaldo tras actualizar: la versión guardada aún tiene las líneas volátiles
prof = get_profile("ubiquiti_edgeswitch")
old_saved = "! System Up Time: 173 days, 17 hours, 45 mins, 28 secs\n! Config Created Time: 2026-10-22 21:07:28 UTC+8\nhostname SW\nvlan 10\n"
new = clean_config("! System Up Time: 174 days, 10 hours, 38 mins, 9 secs\n! Config Created Time: 2026-10-23 14:00:09\nhostname SW\nvlan 10\n", prof)
check("la versión nueva ya no guarda la hora ni el tiempo encendido", "Up Time" not in new and "Created Time" not in new, new)
check("primer respaldo tras actualizar: la versión antigua con hora y tiempo encendido no cuenta como cambio",
      same_config(old_saved, new, prof))
check("pero un cambio real sí", not same_config(old_saved, new.replace("vlan 10", "vlan 20"), prof))

print("\n" + ("TODO OK" if not fails else f"{len(fails)} FALLOS: {fails}"))
sys.exit(1 if fails else 0)
