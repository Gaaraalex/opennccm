# cambio de una clave de /tmp/system.cfg: la reemplaza si existe y la agrega si no
def _cfg(key: str, value: str) -> str:
    return (f"grep -q '^{key}=' /tmp/system.cfg && sed -i 's|^{key}=.*|{key}={value}|' /tmp/system.cfg"
            f" || echo '{key}={value}' >> /tmp/system.cfg")


